const BOLD_H = 10;

/**
 * Bloques del texto en el alfabeto bold: [{ x, y, ci, order }] con y hacia arriba (fila inferior = 0).
 * Las tildes (Á É Í Ó Ú) y la virgulilla (Ñ) ocupan las filas 11–12, con 1 fila libre sobre la letra.
 */
export function boldTextBlocks(text, { spacing = 2 } = {}) {
  const out = [];
  const chars = Array.from(String(text).toUpperCase());
  let ox = 0;
  chars.forEach((ch, ci) => {
    let rows = B[ch], mark = null;
    if (!rows && ACCENT[ch]) { rows = B[ACCENT[ch]]; mark = "acute"; }
    if (!rows && ch === TILDE_N) { rows = B.N; mark = "tilde"; }
    if (!rows) rows = B[" "];
    const w = rows[0].length;
    rows.forEach((row, ri) => { for (let c = 0; c < w; c++) if (row[c] === "#") out.push({ x: ox + c, y: BOLD_H - 1 - ri, ci }); });
    const m = Math.floor(w / 2);
    if (mark === "acute") [[m - 1, 11], [m, 11], [m, 12], [m + 1, 12]].forEach(([x, y]) => out.push({ x: ox + x, y, ci }));
    if (mark === "tilde") {
      [".###..##", "##..###."].forEach((row, k) => { for (let c = 0; c < row.length; c++) if (row[c] === "#") out.push({ x: ox + c, y: 12 - k, ci }); });
    }
    ox += w + spacing;
  });
  const width = Math.max(1, ox - spacing);
  out.sort((a, b) => a.ci - b.ci || a.y - b.y || a.x - b.x);
  out.forEach((b, i) => (b.order = i));
  return { blocks: out, width, height: out.some((b) => b.y >= BOLD_H) ? 13 : BOLD_H };
}

/** Normaliza el texto del monumento: máximo 8 caracteres soportados. */
export function cleanMonumentText(t) {
  return Array.from(String(t || "").toUpperCase()).filter((c) => G[c] || ACCENT[c] || c === TILDE_N).slice(0, 8).join("") || "HOLA";
}
