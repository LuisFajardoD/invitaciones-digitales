// Letras acentuadas: la base + marca arriba (fila -1)
const ACCENT = { "Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U" };
const TILDE_N = "Ñ";

/**
 * Devuelve los bloques de un texto: [{ x, y, char, order }], con y hacia arriba (fila inferior = 0).
 * Ancho por carácter 5 + 1 de espacio.
 */
export function textBlocks(text, { spacing = 1 } = {}) {
  const out = [];
  const chars = Array.from(String(text).toUpperCase());
  chars.forEach((ch, ci) => {
    const ox = ci * (5 + spacing);
    let rows = G[ch];
    let mark = null;
    if (!rows && ACCENT[ch]) { rows = G[ACCENT[ch]]; mark = "acute"; }
    if (!rows && ch === TILDE_N) { rows = G.N; mark = "tilde"; }
    if (!rows) rows = G[" "];
    rows.forEach((row, ri) => {
      for (let c = 0; c < 5; c++) if (row[c] === "#") out.push({ x: ox + c, y: 6 - ri, ci });
    });
    if (mark === "acute") { out.push({ x: ox + 2, y: 8, ci }); out.push({ x: ox + 3, y: 9, ci }); }
    if (mark === "tilde") { [[0, 8], [1, 9], [2, 8], [3, 8], [4, 9]].forEach(([x, y]) => out.push({ x: ox + x, y, ci })); }
  });
  const width = chars.length * (5 + spacing) - spacing;
  // Orden de construcción: letra por letra, de abajo hacia arriba
  out.sort((a, b) => a.ci - b.ci || a.y - b.y || a.x - b.x);
  out.forEach((b, i) => (b.order = i));
  return { blocks: out, width, height: out.some((b) => b.y > 6) ? 10 : 7 };
}

